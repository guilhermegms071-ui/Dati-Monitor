// Command gen generates product_gen.go from the repository-level product.json,
// which is the single source of truth for the product name.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

type productFile struct {
	Name          string `json:"name"`
	Slug          string `json:"slug"`
	ServicePrefix string `json:"service_prefix"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "uso: gen <product.json> <saida.go>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(filepath.Clean(in)) //nolint:gosec // G703: path comes from the go:generate directive, not user input
	if err != nil {
		return err
	}
	var p productFile
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&p); err != nil {
		return fmt.Errorf("product.json inválido: %w", err)
	}
	if p.Name == "" || p.Slug == "" || p.ServicePrefix == "" {
		return fmt.Errorf("product.json: name, slug e service_prefix são obrigatórios")
	}
	src := fmt.Sprintf(`// Code generated by internal/product/gen from product.json. DO NOT EDIT.

package product

const (
	// Name is the human-readable product name.
	Name = %q
	// Slug is the lowercase identifier used in Linux paths and package names.
	Slug = %q
	// ServicePrefix is the prefix of Windows service names and Windows folders.
	ServicePrefix = %q
)
`, p.Name, p.Slug, p.ServicePrefix)
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Clean(out), formatted, 0o600) //nolint:gosec // G703: path comes from the go:generate directive
}
